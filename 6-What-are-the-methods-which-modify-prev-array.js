

// push method :
let arr = [1, 2, 3]
arr.push(4)
console.log(arr) // [1,2,3,4]


// pop method :
let arr1 = [1, 2, 3, 4]
arr1.pop(4)
console.log(arr1) // [1,2,3]


// shift method :
let arr2 = [1, 2, 3]
arr2.shift()
console.log(arr2) // [2,3]

// unshift method : 
let arr3 = [1, 2, 3]
arr3.unshift(4)
console.log(arr3) // [4,1,2,3]

// splice method : 
let arr4 = [1, 2, 3]
arr4.splice(1,2, [8, 9, 10])
console.log(arr4) // [1,[8,9,10]]



// sort method : 
let arr5 = [3, 4, 52, 1, 0]
arr5.sort()
console.log(arr5) // [ 0, 1, 3, 4, 52 ]


// reverse method : 
let arr6 = [1, 2, 3, 4, 5]
arr6.reverse()
console.log(arr6) // [ 5, 4, 3, 2, 1 ]


// fill method : 
let arr7 = [1,2,3,4,5]
arr7.fill(0)
console.log(arr7) // [ 0, 0, 0, 0, 0 ]


